# s43 Track A: species lookups for ME and MN. The firebreather 7 Oct rebuild built them "from the shared crosswalk
# restricted to each state's species.txt" (MEMORY session 38). species_crosswalk_NE_LS_20260929.csv is not on Cardinal;
# its rows are embedded in species_lookup_<ST>.R of NH, VT (NE pool, ME template) and MI, WI (LS pool). ME = NH+VT rows,
# MN = MI+WI rows, each restricted to the state's species.txt codes. Conflicting SPCD mappings stop the script.
suppressMessages(library(data.table))
D <- "/fs/scratch/PUOM0008/crsfaaron/landis2/states_fb_20260930"; L <- "/fs/scratch/PUOM0008/crsfaaron/landis2/states"
T <- "/fs/scratch/PUOM0008/crsfaaron/ncasi_gates_20261015/s43/landis_memn/out"
emb <- function(st) { e <- new.env(); sys.source(file.path(D, st, "inputs", paste0("species_lookup_", st, ".R")), envir = e); as.data.table(e$SPECIES_LOOKUP)[, src := st] }
for (x in list(c("ME", "NH", "VT"), c("MN", "MI", "WI"))) {
  st <- x[1]; u <- rbind(emb(x[2]), emb(x[3]), fill = TRUE)
  conf <- u[, uniqueN(LANDIS), by = SPCD][V1 > 1]; if (nrow(conf)) stop(st, " conflicting SPCD: ", paste(conf$SPCD, collapse = " "))
  sp <- readLines(file.path(L, st, "inputs/species.txt")); sp <- sp[!grepl("^>>|LandisData|^\\s*$", sp)]
  codes <- unique(sapply(strsplit(trimws(sp), "\\s+"), `[`, 1))
  u <- unique(u[LANDIS %in% codes], by = "SPCD")[order(SPCD)]
  cat(st, "species.txt codes", length(codes), "lookup rows", nrow(u), "codes used", uniqueN(u$LANDIS), "missing:", setdiff(codes, u$LANDIS), "\n")
  fwrite(u, file.path(T, paste0("species_lookup_", st, "_s43.csv")))
  writeLines(c(paste0("# species_lookup_", st, "_s43.R generated by make_lookups_s43.R (s43 Track A) from embedded NE/LS crosswalk rows"),
    sprintf("SPECIES_LOOKUP <- data.table::data.table(SPCD = c(%s), LANDIS = c(%s))", paste(u$SPCD, collapse = ", "), paste0('"', u$LANDIS, '"', collapse = ", "))),
    file.path(T, paste0("species_lookup_", st, "_s43.R")))
}
